function main() {
  const outPath = path.join(process.cwd(), "docs", "geo-place-resolver-shadow-eval-2026-06-18.md");
  const lines: string[] = [];
  lines.push("# Geo Place Resolver Shadow Eval - 2026-06-18");
  lines.push("");
  lines.push("Generated by `npx tsx scripts/eval-geo-place-resolver.ts`.");
  lines.push("");
  lines.push("This resolver is dark-launched: these results are not used by the UI, router, prompts, or SQL handlers.");
  lines.push("");
  lines.push("| Case | Query | Expected | Resolver Output | Clarifies |");
  lines.push("| --- | --- | --- | --- | --- |");

  for (const testCase of CASES) {
    const result = resolveGeoPlaces(testCase.query);
    const output = result.mentions.length
      ? result.mentions.map((mention) => {
        const candidates = mention.candidates
          .map((candidate) => `${candidate.id} (${candidate.confidence.toFixed(2)})`)
          .join("<br>");
        return `**${escapePipes(mention.text)}**<br>${candidates}`;
      }).join("<br><br>")
      : "none";
    lines.push(`| ${testCase.id} | ${escapePipes(testCase.query)} | ${escapePipes(testCase.expected)} | ${output} | ${result.requiresClarification ? "yes" : "no"} |`);
  }

  lines.push("");
  lines.push("## Promotion Notes");
  lines.push("");
  lines.push("- Safe next step: keep adding eval cases from query logs while resolver remains shadow-only.");
  lines.push("- Do not wire this into pre-submit guidance until false positives are reviewed, especially broad multi-state city names.");
  lines.push("- Do not wire this into SQL generation directly; use it first as structured geography intent.");
  lines.push("");

  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, `${lines.join("\n")}\n`, "utf8");
  console.log(`Wrote ${outPath}`);
}

function escapePipes(value: string) {
  return value.replace(/\|/g, "\\|");
}

main();
