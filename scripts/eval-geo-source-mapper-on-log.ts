import Database from "better-sqlite3";
import fs from "node:fs";
import path from "node:path";
import { resolveGeoPlaces } from "../lib/geo-place-resolver";
import { mapGeoResolutionToSources, type GeoSource, type GeoSourceMapStatus } from "../lib/geo-source-mapper";

type QueryLogRow = {
  id?: number;
  ts: number;
  tab?: string | null;
  question: string;
};

const SOURCES: GeoSource[] = ["current", "historical", "nibrs", "shr"];
const STATUSES: GeoSourceMapStatus[] = ["safe_exact", "needs_clarification", "unsupported", "dangerous_scope", "unknown"];

function argValue(name: string): string | null {
  const prefix = `${name}=`;
  const found = process.argv.find((arg) => arg.startsWith(prefix));
  return found ? found.slice(prefix.length) : null;
}

function days(): number {
  const raw = argValue("--days");
  const parsed = raw ? Number(raw) : 1;
  return Number.isFinite(parsed) && parsed > 0 ? parsed : 1;
}

function errorsOnly(): boolean {
  return process.argv.includes("--errors-only");
}

function outPath(): string {
  const explicit = argValue("--out");
  if (explicit) return explicit;
  const stamp = new Date().toISOString().slice(0, 10);
  const suffix = errorsOnly() ? "error-frame" : "log-frame";
  return path.join(process.cwd(), "docs", `geo-source-mapper-${suffix}-${stamp}.md`);
}

function openOptionalDb(file: string | null): Database.Database | null {
  if (!file) return null;
  try {
    return new Database(file, { readonly: true, fileMustExist: true });
  } catch {
    return null;
  }
}

function main() {
  const logPath = argValue("--db") || path.join(process.cwd(), "query_log.db");
  const rtciPath = argValue("--rtci-db") || path.join(process.cwd(), "crime_data.db");
  const nibrsPath = argValue("--nibrs-db") || path.join(process.cwd(), "nibrs.db");
  const shrPath = argValue("--shr-db") || path.join(process.cwd(), "shr.db");
  const cutoff = Date.now() - days() * 24 * 60 * 60 * 1000;
  const logDb = new Database(logPath, { readonly: true, fileMustExist: true });
  const dbs = {
    currentHistorical: openOptionalDb(rtciPath),
    nibrs: openOptionalDb(nibrsPath),
    shr: openOptionalDb(shrPath),
  };

  try {
    const hasId = columnExists(logDb, "query_log", "id");
    const idSelect = hasId ? "id" : "rowid AS id";
    const errorClause = errorsOnly() ? "AND error IS NOT NULL AND length(error) > 0" : "";
    const rows = logDb.prepare(`
      SELECT ${idSelect}, ts, tab, question
      FROM query_log
      WHERE ts >= ? AND question IS NOT NULL AND question <> ''
      ${errorClause}
      ORDER BY ts ASC
    `).all(cutoff) as QueryLogRow[];

    writeReport({
      rows,
      target: outPath(),
      logPath,
      dbPaths: { rtciPath, nibrsPath, shrPath },
      windowDays: days(),
      cutoff,
      errorsOnly: errorsOnly(),
      dbs,
    });
  } finally {
    logDb.close();
    dbs.currentHistorical?.close();
    dbs.nibrs?.close();
    dbs.shr?.close();
  }
}

function columnExists(db: Database.Database, table: string, column: string): boolean {
  return db.prepare(`PRAGMA table_info(${table})`).all()
    .some((row) => (row as { name?: string }).name === column);
}

function writeReport(opts: {
  rows: QueryLogRow[];
  target: string;
  logPath: string;
  dbPaths: { rtciPath: string; nibrsPath: string; shrPath: string };
  windowDays: number;
  cutoff: number;
  errorsOnly: boolean;
  dbs: {
    currentHistorical: Database.Database | null;
    nibrs: Database.Database | null;
    shr: Database.Database | null;
  };
}) {
  const counts = new Map<string, number>();
  let withPlaces = 0;
  let candidates = 0;
  const evaluated = opts.rows.map((row) => {
    const resolution = resolveGeoPlaces(row.question);
    if (resolution.mentions.length > 0) withPlaces += 1;
    const mappings = mapGeoResolutionToSources(resolution, opts.dbs);
    candidates += mappings.length;
    for (const item of mappings) {
      for (const mapping of item.mappings) {
        const key = `${mapping.source}:${mapping.status}`;
        counts.set(key, (counts.get(key) || 0) + 1);
      }
    }
    return { row, resolution, mappings };
  });

  const lines: string[] = [];
  lines.push(`# Geo Source Mapper ${opts.errorsOnly ? "Error Frame" : "Log Frame"} - ${new Date().toISOString().slice(0, 10)}`);
  lines.push("");
  lines.push("Generated by `npx tsx scripts/eval-geo-source-mapper-on-log.ts`.");
  lines.push("");
  lines.push("- Shadow-only: no app behavior is changed.");
  lines.push(`- Query log: \`${opts.logPath}\``);
  lines.push(`- RTCI/Historical DB: \`${opts.dbPaths.rtciPath}\``);
  lines.push(`- NIBRS DB: \`${opts.dbPaths.nibrsPath}\``);
  lines.push(`- SHR DB: \`${opts.dbPaths.shrPath}\``);
  lines.push(`- Window: last ${opts.windowDays} day(s), since ${new Date(opts.cutoff).toISOString()}`);
  if (opts.errorsOnly) lines.push("- Filter: rows with non-empty `error` only");
  lines.push(`- Queries evaluated: ${opts.rows.length}`);
  lines.push(`- Queries with place mentions: ${withPlaces}`);
  lines.push(`- Place candidates evaluated: ${candidates}`);
  lines.push("");
  lines.push("## Status Counts");
  lines.push("");
  lines.push("| Source | Safe Exact | Clarify | Unsupported | Dangerous Scope | Unknown |");
  lines.push("| --- | ---: | ---: | ---: | ---: | ---: |");
  for (const source of SOURCES) {
    lines.push(`| ${source} | ${STATUSES.map((status) => counts.get(`${source}:${status}`) || 0).join(" | ")} |`);
  }
  lines.push("");
  lines.push("## Rows");
  lines.push("");
  lines.push("| Log | Time | Tab | Question | Candidate | Source Map |");
  lines.push("| --- | --- | --- | --- | --- | --- |");

  for (const { row, mappings } of evaluated) {
    if (mappings.length === 0 && opts.rows.length > 100) continue;
    const candidateText = mappings.length
      ? mappings.map((item) => `${escapeCell(item.mentionText)} -> ${item.candidate.id}`).join("<br>")
      : "none";
    const sourceText = mappings.length
      ? mappings.map((item) => item.mappings.map((mapping) => {
        const matchCount = mapping.matches.length ? ` (${mapping.matches.length} match${mapping.matches.length === 1 ? "" : "es"})` : "";
        return `${mapping.source}: ${mapping.status}${matchCount}`;
      }).join("<br>")).join("<br><br>")
      : "none";
    lines.push(`| ${row.id ?? ""} | ${new Date(row.ts).toISOString()} | ${escapeCell(row.tab ?? "")} | ${escapeCell(row.question)} | ${candidateText} | ${sourceText} |`);
  }

  lines.push("");
  lines.push("## Review Notes");
  lines.push("");
  lines.push("- `safe_exact` means the source has an explicit state/city/countywide filter path for that resolved candidate.");
  lines.push("- `unknown` means the local eval could not see the required DB/table; it is not proof of unsupported geography.");
  lines.push("- This report is a source-contract audit only. It does not rewrite queries or change routing.");
  lines.push("");

  fs.mkdirSync(path.dirname(opts.target), { recursive: true });
  fs.writeFileSync(opts.target, `${lines.join("\n")}\n`, "utf8");
  console.log(`Wrote ${opts.target}`);
  console.log(`queries=${opts.rows.length} withPlaces=${withPlaces} candidates=${candidates}`);
}

function escapeCell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

main();
