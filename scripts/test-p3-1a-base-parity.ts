/**
 * P3.1a — the flags-off regression: the post-SQL validator still behaves exactly as it did at BASE.
 *
 * WHY SET MEMBERSHIP WAS NOT ENOUGH. Moving BLOCK_CAPABILITY_RULES and RETRY_CAPABILITY_RULES into
 * `lib/capability-decision.ts` can be membership-preserving and still change behaviour: the branch
 * order could invert, a block message could be selected differently, or an id could land in
 * `enforced` under the other class. Asserting the two sets are equal would catch none of that.
 *
 * So this compares OUTPUT. The frozen baseline in
 * `scripts/fixtures/p3-1a-base-postsql-baseline.json` was generated by running
 * `scripts/lib-p3-1a-postsql-grid.ts` in a detached worktree at BASE
 * `e2d24acd37027f436590ed8eae58bb5b30414ffb` — before the extraction existed.
 *
 * AFTER THE PHASE 3 INTEGRATION (2026-09-30) THERE ARE TWO PARENTS. The accepted Phase 3 candidate
 * changed post-SQL behaviour on purpose (structural semantics, the vehicle-burglary rule, contract
 * resolution), so "identical to BASE" no longer describes the correct tree. Neither does "equal to
 * BASE OR to the candidate": that would let a repaired cell regress to old BASE behaviour. So every
 * cell has ONE expected result:
 *
 *   - the pinned CANDIDATE result (`scripts/fixtures/p3-1a-candidate-postsql-grid.json`, generated
 *     from committed 9dbbda3 by the same grid -- see its `_provenance`) on every field the candidate
 *     carries, for every cell except the declared composed cells; and
 *   - for the four DECLARED composed cells, the explicit merge of the candidate result with dev's
 *     authored decision at BASE (`composeMergeResult` below: dev's source-specific block reasons
 *     first, then the candidate's structural ones; enforced ids unioned; no retry once blocked).
 *
 * dev-only fields are asserted separately: `clearanceGrainObservation` equals BASE on every cell, and
 * `capabilityOutcome` keeps its own assertions. Extra or missing keys or cells fail. BASE is never
 * regenerated or edited.
 *
 * ADEQUACY IS ASSERTED, NOT ASSUMED. A grid that fired nothing would compare two empty results and
 * pass forever. The controls below pin how many rows actually block, how many retry, and that both
 * classes of enforced id are represented, and two substitution controls require the comparison to
 * notice a parent's result standing in for the expected one.
 *
 * Deterministic. No database, no model, no network, no production.
 */
import fs from "node:fs";
import path from "node:path";
import { runPostSqlGrid, GRID_SOURCES, GRID_QUESTIONS, GRID_SQLS, type GridRow } from "./lib-p3-1a-postsql-grid";
import { BLOCK_CAPABILITY_RULES, RETRY_CAPABILITY_RULES } from "../lib/capability-decision";
import { OUTCOMES } from "../lib/proof-contract";

const BASE_TREE = "e2d24acd37027f436590ed8eae58bb5b30414ffb";
const BASELINE = path.join(__dirname, "fixtures", "p3-1a-base-postsql-baseline.json");
const CANDIDATE_GRID = path.join(__dirname, "fixtures", "p3-1a-candidate-postsql-grid.json");

let pass = 0, fail = 0;
function check(name: string, actual: unknown, expected: unknown) {
  const a = JSON.stringify(actual), e = JSON.stringify(expected);
  if (a === e) { pass++; console.log(`  ok    ${name}`); }
  else { fail++; console.log(`  FAIL  ${name}\n          got      ${a}\n          expected ${e}`); }
}
function checkTrue(name: string, cond: boolean, detail?: string) {
  if (cond) { pass++; console.log(`  ok    ${name}`); }
  else { fail++; console.log(`  FAIL  ${name}${detail ? "\n          " + detail : ""}`); }
}

/**
 * Keys the candidate ADDS to the BASE result shape. Declared here, one line, deliberately awkward
 * to extend.
 *
 * The baseline is NOT regenerated when a field is added — regenerating would destroy the only
 * evidence that BASE behaviour is unchanged, which is the whole point of the file. Instead every
 * BASE key is compared exactly, the key-set difference must equal this list, and the added key gets
 * its own assertions below. Adding a key to this list without those assertions is how the
 * regression would quietly stop meaning anything.
 *
 * `capabilityOutcome` carries the typed catalog pair that `classifyCapabilityRule()` returns for a
 * fired block rule, so the shared classification is observable at runtime instead of only by
 * reading four route files.
 */
const ADDED_KEYS = ["capabilityOutcome"] as const;
/** BASE keys the Phase 3 candidate never had (dev added them after the fork). Asserted against BASE. */
const DEV_ONLY_BASE_KEYS = ["clearanceGrainObservation"] as const;
/** Block rules added after BASE by accepted work (see test-request-decision-observer's ADDED_BLOCK_RULES). */
const ADDED_BLOCK_RULE_COUNT = 1;   // vehicle-burglary-unsupported

const baseline: GridRow[] = JSON.parse(fs.readFileSync(BASELINE, "utf8"));
const candidate: GridRow[] = JSON.parse(fs.readFileSync(CANDIDATE_GRID, "utf8")).rows;
const current = runPostSqlGrid();

const BASE_KEYS = Object.keys(baseline[0].result).sort();
const CANDIDATE_KEYS = Object.keys(candidate[0].result).sort();
const cellKey = (r: { source: string; question: string; sql: string }) => `${r.source}\u0001${r.question}\u0001${r.sql}`;

/**
 * The four cells where the merged validator must equal neither parent, each named with its reason.
 * Any OTHER cell that differs from the candidate fails -- a new interaction cannot hide here.
 */
const COMPOSED_CELLS: { source: string; question: string; sql: string; why: string }[] = [
  { source: "historical", question: "How many people were sentenced for homicide in Cook County in 2023?",
    sql: "WITH x AS (SELECT 1) SELECT murders FROM historical_agency_clearance JOIN x",
    why: "court-topic refusal now precedes the candidate's generic structural message (order only)" },
  { source: "historical", question: "How many murders were cleared in Louisiana in 2019?",
    sql: "SELECT COUNT(*) FROM summary_state_monthly WHERE state='IL'",
    why: "dev's authored statewide-clearance decline blocks; the candidate only retried" },
  { source: "historical", question: "How many murders were cleared in Louisiana in 2019?",
    sql: "WITH x AS (SELECT 1) SELECT murders FROM historical_agency_clearance JOIN x",
    why: "dev's authored decline first, then the candidate's two structural blocks" },
  { source: "historical", question: "How many murders were cleared in Louisiana in 2019?",
    sql: "SELECT year, murders FROM national_monthly ORDER BY year",
    why: "dev's authored statewide-clearance decline blocks; the candidate only retried" },
];
const COMPOSED = new Set(COMPOSED_CELLS.map(cellKey));

const pick = (r: Record<string, unknown> | undefined, keys: readonly string[]) => {
  const out: Record<string, unknown> = {};
  for (const k of keys) out[k] = r?.[k];
  return out;
};
const strs = (v: unknown) => (Array.isArray(v) ? (v as string[]) : []);

/** The explicit merge rule for a declared composed cell, on the candidate's keys. */
function composeMergeResult(cand: Record<string, unknown>, base: Record<string, unknown>) {
  const baseBlocks = strs(base.blockReasons);
  const blockReasons = [...baseBlocks, ...strs(cand.blockReasons).filter((m) => !baseBlocks.includes(m))];
  const candEnforced = strs(cand.enforced);
  const enforced = [...candEnforced, ...strs(base.enforced).filter((id) => !candEnforced.includes(id))];
  return { ...pick(cand, CANDIDATE_KEYS), blockReasons, enforced,
    retryIssues: blockReasons.length > 0 ? [] : cand.retryIssues };
}

/** The ONE expected result per cell, on the candidate's keys. */
const expected: Record<string, unknown>[] = candidate.map((c, i) =>
  COMPOSED.has(cellKey(c)) ? composeMergeResult(c.result, baseline[i].result) : pick(c.result, CANDIDATE_KEYS));

/** Cells whose actual result is not the expected one (candidate keys only). */
function mismatches(actual: GridRow[]): number[] {
  const out: number[] = [];
  for (let i = 0; i < expected.length; i++) {
    if (JSON.stringify(pick(actual[i]?.result, CANDIDATE_KEYS)) !== JSON.stringify(expected[i])) out.push(i);
  }
  return out;
}

console.log(`P3.1a post-SQL regression: BASE ${BASE_TREE.slice(0, 12)} + pinned Phase 3 candidate, per cell`);

// ── the grid is what both fixtures were generated from ─────────────────────────────────────
check("grid shape unchanged since the baseline was captured",
  [GRID_SOURCES.length, GRID_QUESTIONS.length, GRID_SQLS.length,
   GRID_SOURCES.length * GRID_QUESTIONS.length * GRID_SQLS.length],
  [5, 15, 3, 225]);
check("the baseline holds one row per grid cell", baseline.length, 225);
check("the candidate grid holds one row per grid cell", candidate.length, 225);
check("the current run produces the same number of rows", current.length, baseline.length);
checkTrue("all three grids list the same cells in the same order",
  current.every((r, i) => cellKey(r) === cellKey(baseline[i]) && cellKey(r) === cellKey(candidate[i])));
check("every declared composed cell exists in the grid",
  COMPOSED_CELLS.filter((c) => !baseline.some((b) => cellKey(b) === cellKey(c))).length, 0);

// ── key sets: nothing extra, nothing missing ────────────────────────────────────────────────
check("the candidate carries exactly BASE's keys minus the dev-only ones",
  CANDIDATE_KEYS, BASE_KEYS.filter((k) => !(DEV_ONLY_BASE_KEYS as readonly string[]).includes(k)));
checkTrue("every current row has exactly BASE's keys plus the declared added keys",
  current.every((r) => JSON.stringify(Object.keys(r.result).sort()) === JSON.stringify([...BASE_KEYS, ...ADDED_KEYS].sort())));

// ── adequacy: BASE and the expected grid both reach the code under test ─────────────────────
{
  const tally = (rows: { blockReasons?: unknown; retryIssues?: unknown; enforced?: unknown }[]) => {
    const ids = new Set<string>();
    for (const r of rows) for (const id of strs(r.enforced)) ids.add(id);
    return [rows.filter((r) => strs(r.blockReasons).length).length,
      rows.filter((r) => strs(r.retryIssues).length).length, ids.size, ids] as const;
  };
  const [bBlock, bRetry, bIds] = tally(baseline.map((r) => r.result));
  check("BASE: rows reaching a block reason / a retry issue / distinct enforced ids", [bBlock, bRetry, bIds], [72, 138, 17]);
  const [eBlock, eRetry, eIds, eSet] = tally(expected);
  check("expected merged grid: rows reaching a block reason / a retry issue / distinct enforced ids",
    [eBlock, eRetry, eIds], [76, 148, 22]);
  check("the grid exercises both classes, not just one", [eBlock > 0, eRetry > 0], [true, true]);
  checkTrue("enforced ids include members of BOTH the block and the retry set",
    [...eSet].some((id) => BLOCK_CAPABILITY_RULES.has(id)) && [...eSet].some((id) => RETRY_CAPABILITY_RULES.has(id)));
}

// ── the declared composed cells are real, and are the only ones ─────────────────────────────
{
  const realComposition = COMPOSED_CELLS.every((c) => {
    const i = candidate.findIndex((r) => cellKey(r) === cellKey(c));
    const e = JSON.stringify(expected[i]);
    return e !== JSON.stringify(pick(candidate[i].result, CANDIDATE_KEYS))
      && e !== JSON.stringify(pick(baseline[i].result, CANDIDATE_KEYS));
  });
  checkTrue("each declared composed cell differs from BOTH parents (no decorative declaration)", realComposition);
  // Supporting accounting only (Codex 2026-09-30): not an alternative to the per-cell check below.
  let equalBase = 0, equalCandidate = 0, composed = 0;
  expected.forEach((e, i) => {
    const s = JSON.stringify(e);
    if (s === JSON.stringify(pick(baseline[i].result, CANDIDATE_KEYS))) equalBase++;
    else if (COMPOSED.has(cellKey(candidate[i]))) composed++;
    else equalCandidate++;
  });
  check("accounting: expected equals BASE / the candidate (differing from BASE) / composed", [equalBase, equalCandidate, composed], [2, 219, 4]);
}

// ── THE comparison: every cell equals its one expected result ───────────────────────────────
{
  const bad = mismatches(current);
  const detail = bad.slice(0, 3).map((i) => {
    const changed = CANDIDATE_KEYS.filter((k) => JSON.stringify(current[i].result[k]) !== JSON.stringify(expected[i][k]));
    return `row ${i} [${current[i].source}] "${current[i].question.slice(0, 48)}…" ${COMPOSED.has(cellKey(current[i])) ? "(composed) " : ""}changed: ${changed.join(", ")}`;
  });
  checkTrue("every post-SQL result equals its one expected result, on every field the candidate carries",
    bad.length === 0, `${bad.length} row(s) differ\n          ` + detail.join("\n          "));
  checkTrue("dev's clearance-grain observation equals BASE on every cell",
    current.every((r, i) => JSON.stringify(r.result.clearanceGrainObservation) === JSON.stringify(baseline[i].result.clearanceGrainObservation)));
  const grainCells = current.filter((r) => r.result.clearanceGrainObservation != null).length;
  checkTrue("and that observation is present on some cells, so the check is not vacuous", grainCells > 0, `${grainCells} cells`);
}

// ── the fields the review named, compared as inventories as well as row-wise ────────────────
{
  const inventory = (rows: Record<string, unknown>[], key: string) => {
    const s = new Set<string>();
    for (const r of rows) for (const v of (r[key] as unknown[]) ?? []) s.add(typeof v === "string" ? v : JSON.stringify(v));
    return [...s].sort();
  };
  for (const key of ["warnings", "blockReasons", "retryIssues", "enforced", "capabilityFindings"]) {
    check(`inventory of ${key} equals the expected merged grid's`, inventory(current.map((r) => r.result), key), inventory(expected, key));
  }
}

// ── SUBSTITUTION CONTROLS: a parent's result standing in for the expected one must fail ─────
{
  // (a) Every cell the candidate changed from BASE: put BASE's result back and require a failure
  //     AT THAT CELL. This is the regression "BASE or candidate" would have let through.
  const changedFromBase = candidate.map((c, i) => i).filter((i) =>
    JSON.stringify(pick(candidate[i].result, CANDIDATE_KEYS)) !== JSON.stringify(pick(baseline[i].result, CANDIDATE_KEYS)));
  let caught = 0;
  for (const i of changedFromBase) {
    const swapped = current.map((r, j) => (j === i ? { ...r, result: { ...r.result, ...pick(baseline[i].result, CANDIDATE_KEYS) } } : r));
    if (mismatches(swapped).includes(i)) caught++;
  }
  checkTrue("substituting BASE's old result into any candidate-changed cell FAILS (every one)",
    changedFromBase.length > 0 && caught === changedFromBase.length,
    `${caught} of ${changedFromBase.length} substitutions caught`);
  // (b) Every composed cell: the bare candidate result must not pass for the composition.
  let caughtComposed = 0;
  for (const c of COMPOSED_CELLS) {
    const i = candidate.findIndex((r) => cellKey(r) === cellKey(c));
    const swapped = current.map((r, j) => (j === i ? { ...r, result: { ...r.result, ...pick(candidate[i].result, CANDIDATE_KEYS) } } : r));
    if (mismatches(swapped).includes(i)) caughtComposed++;
  }
  check("substituting the bare candidate result into each composed cell FAILS", caughtComposed, COMPOSED_CELLS.length);
}

// ── the added key: asserted, never merely permitted ─────────────────────────────────────────
{
  const withOutcome = current.filter((r) => r.result.capabilityOutcome != null);
  const withCapabilityBlock = current.filter((r) =>
    ((r.result.enforced as string[]) ?? []).some((id) => BLOCK_CAPABILITY_RULES.has(id)));

  check("capabilityOutcome is non-null on exactly the rows a capability BLOCK rule enforced",
    [withOutcome.length, withCapabilityBlock.length, withOutcome.length > 0],
    [withCapabilityBlock.length, withCapabilityBlock.length, true]);
  checkTrue("every non-null capabilityOutcome is the shared catalog OBJECT, not a copy",
    withOutcome.every((r) => r.result.capabilityOutcome === OUTCOMES.query_contract_failed));
  checkTrue("a row carrying capabilityOutcome always carries a block reason too",
    withOutcome.every((r) => ((r.result.blockReasons as string[]) ?? []).length > 0));
  checkTrue("a row with no capability block carries null, not an empty object",
    current.filter((r) => !withCapabilityBlock.includes(r))
      .every((r) => r.result.capabilityOutcome === null));
}

// ── ANTI-VACUITY: the comparison must be able to go red ─────────────────────────────────────
// A parity test that has never been observed failing is evidence that it runs, not that the
// property holds. This reclassifies one rule from block to retry through the shared authority —
// membership-preserving in total size, behaviour-changing in fact — and requires the comparison to
// notice. Then it restores and requires the comparison to be clean again.
{
  const victim = "unsupported-sub-city-geography";
  const wasBlock = BLOCK_CAPABILITY_RULES.has(victim);
  const countRowDiffs = () => mismatches(runPostSqlGrid()).length;

  checkTrue("anti-vacuity precondition: the victim rule is a block rule at rest", wasBlock);
  let underMutation = -1;
  try {
    BLOCK_CAPABILITY_RULES.delete(victim);
    RETRY_CAPABILITY_RULES.add(victim);
    underMutation = countRowDiffs();
  } finally {
    RETRY_CAPABILITY_RULES.delete(victim);
    if (wasBlock) BLOCK_CAPABILITY_RULES.add(victim);
  }

  checkTrue("reclassifying one rule block -> retry makes the comparison go RED",
    underMutation > 0, `it stayed green across all ${baseline.length} rows, so it proves nothing`);
  check("and the comparison is clean again once the authority is restored", countRowDiffs(), 0);
  check("the shared sets are restored exactly",
    [BLOCK_CAPABILITY_RULES.has(victim), RETRY_CAPABILITY_RULES.has(victim),
     BLOCK_CAPABILITY_RULES.size, RETRY_CAPABILITY_RULES.size],
    [true, false, 9 + ADDED_BLOCK_RULE_COUNT, 28]);
}

console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail === 0 ? 0 : 1);
