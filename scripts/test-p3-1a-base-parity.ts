/**
 * P3.1a — the flags-off regression: the post-SQL validator still behaves exactly as it did at BASE.
 *
 * WHY SET MEMBERSHIP WAS NOT ENOUGH. Moving BLOCK_CAPABILITY_RULES and RETRY_CAPABILITY_RULES into
 * `lib/capability-decision.ts` can be membership-preserving and still change behaviour: the branch
 * order could invert, a block message could be selected differently, or an id could land in
 * `enforced` under the other class. Asserting the two sets are equal would catch none of that.
 *
 * So this compares OUTPUT. The frozen baseline in
 * `scripts/fixtures/p3-1a-base-postsql-baseline.json` was generated by running
 * `scripts/lib-p3-1a-postsql-grid.ts` in a detached worktree at BASE
 * `e2d24acd37027f436590ed8eae58bb5b30414ffb` — before the extraction existed. This test reruns the
 * same grid against the current tree and requires the two to be identical, key for key, across
 * findings, retry issues, block reasons, enforced ids and every other field the result carries.
 *
 * ADEQUACY IS ASSERTED, NOT ASSUMED. A grid that fired nothing would compare two empty results and
 * pass forever. The controls below pin how many rows actually block, how many retry, and that both
 * classes of enforced id are represented — so the comparison cannot decay into a tautology.
 *
 * Deterministic. No database, no model, no network, no production.
 */
import fs from "node:fs";
import path from "node:path";
import { runPostSqlGrid, GRID_SOURCES, GRID_QUESTIONS, GRID_SQLS, type GridRow } from "./lib-p3-1a-postsql-grid";
import { BLOCK_CAPABILITY_RULES, RETRY_CAPABILITY_RULES } from "../lib/capability-decision";
import { OUTCOMES } from "../lib/proof-contract";

const BASE_TREE = "e2d24acd37027f436590ed8eae58bb5b30414ffb";
const BASELINE = path.join(__dirname, "fixtures", "p3-1a-base-postsql-baseline.json");

let pass = 0, fail = 0;
function check(name: string, actual: unknown, expected: unknown) {
  const a = JSON.stringify(actual), e = JSON.stringify(expected);
  if (a === e) { pass++; console.log(`  ok    ${name}`); }
  else { fail++; console.log(`  FAIL  ${name}\n          got      ${a}\n          expected ${e}`); }
}
function checkTrue(name: string, cond: boolean, detail?: string) {
  if (cond) { pass++; console.log(`  ok    ${name}`); }
  else { fail++; console.log(`  FAIL  ${name}${detail ? "\n          " + detail : ""}`); }
}

/**
 * Keys the candidate ADDS to the BASE result shape. Declared here, one line, deliberately awkward
 * to extend.
 *
 * The baseline is NOT regenerated when a field is added — regenerating would destroy the only
 * evidence that BASE behaviour is unchanged, which is the whole point of the file. Instead every
 * BASE key is compared exactly, the key-set difference must equal this list, and the added key gets
 * its own assertions below. Adding a key to this list without those assertions is how the
 * regression would quietly stop meaning anything.
 *
 * `capabilityOutcome` carries the typed catalog pair that `classifyCapabilityRule()` returns for a
 * fired block rule, so the shared classification is observable at runtime instead of only by
 * reading four route files.
 */
const ADDED_KEYS = ["capabilityOutcome"] as const;

const baseline: GridRow[] = JSON.parse(fs.readFileSync(BASELINE, "utf8"));
const current = runPostSqlGrid();

/** A row's result restricted to the keys BASE had, for exact comparison. */
function baseKeysOnly(result: Record<string, unknown> | undefined, baseKeys: string[]) {
  const out: Record<string, unknown> = {};
  for (const k of baseKeys) out[k] = result?.[k];
  return out;
}
const BASE_KEYS = Object.keys(baseline[0].result).sort();

console.log(`P3.1a flags-off regression against BASE ${BASE_TREE.slice(0, 12)}`);

// ── the grid is what the baseline was generated from ────────────────────────────────────────
check("grid shape unchanged since the baseline was captured",
  [GRID_SOURCES.length, GRID_QUESTIONS.length, GRID_SQLS.length,
   GRID_SOURCES.length * GRID_QUESTIONS.length * GRID_SQLS.length],
  [5, 15, 3, 225]);
check("the baseline holds one row per grid cell", baseline.length, 225);
check("the current run produces the same number of rows", current.length, baseline.length);

// ── the grid is adequate: it actually reaches the code under test ───────────────────────────
{
  const blocked = current.filter((r) => ((r.result.blockReasons as unknown[]) ?? []).length).length;
  const retried = current.filter((r) => ((r.result.retryIssues as unknown[]) ?? []).length).length;
  const enforced = new Set<string>();
  for (const r of current) for (const id of (r.result.enforced as string[]) ?? []) enforced.add(id);

  check("the grid exercises both classes, not just one", [blocked > 0, retried > 0], [true, true]);
  check("rows reaching a block reason", blocked, 72);
  check("rows reaching a retry issue", retried, 138);
  check("distinct enforced ids observed", enforced.size, 17);
  checkTrue("enforced ids include members of BOTH the block and the retry set",
    [...enforced].some((id) => BLOCK_CAPABILITY_RULES.has(id)) &&
    [...enforced].some((id) => RETRY_CAPABILITY_RULES.has(id)));
}

// ── the comparison itself, row by row, with a diagnosable first difference ──────────────────
{
  let differing = 0;
  const firstDiffs: string[] = [];
  for (let i = 0; i < Math.max(baseline.length, current.length); i++) {
    const b = baseline[i], c = current[i];
    // Compared on BASE's key set only; the added key is asserted separately below.
    const bs = JSON.stringify({ ...b, result: baseKeysOnly(b?.result, BASE_KEYS) });
    const cs = JSON.stringify({ ...c, result: baseKeysOnly(c?.result, BASE_KEYS) });
    if (bs === cs) continue;
    differing++;
    if (firstDiffs.length < 3) {
      const changed = BASE_KEYS.filter(
        (k) => JSON.stringify(b?.result?.[k]) !== JSON.stringify(c?.result?.[k]));
      firstDiffs.push(
        `row ${i} [${c?.source ?? b?.source}] "${(c?.question ?? b?.question ?? "").slice(0, 48)}…" ` +
        `changed: ${changed.join(", ") || "row identity"}`);
    }
  }
  checkTrue("every post-SQL result is identical to BASE on every key BASE had",
    differing === 0, `${differing} row(s) differ\n          ` + firstDiffs.join("\n          "));
}

// ── the fields the review named, compared as inventories as well as row-wise ────────────────
{
  const inventory = (rows: GridRow[], key: string) => {
    const s = new Set<string>();
    for (const r of rows) {
      for (const v of (r.result[key] as unknown[]) ?? []) {
        s.add(typeof v === "string" ? v : JSON.stringify(v));
      }
    }
    return [...s].sort();
  };
  for (const key of ["warnings", "blockReasons", "retryIssues", "enforced", "capabilityFindings"]) {
    check(`inventory of ${key} unchanged from BASE`, inventory(current, key), inventory(baseline, key));
  }
  check("the result gained exactly the declared keys and lost none",
    Object.keys(current[0].result).sort(),
    [...BASE_KEYS, ...ADDED_KEYS].sort());
}

// ── the added key: asserted, never merely permitted ─────────────────────────────────────────
{
  const withOutcome = current.filter((r) => r.result.capabilityOutcome != null);
  const withCapabilityBlock = current.filter((r) =>
    ((r.result.enforced as string[]) ?? []).some((id) => BLOCK_CAPABILITY_RULES.has(id)));

  check("capabilityOutcome is non-null on exactly the rows a capability BLOCK rule enforced",
    [withOutcome.length, withCapabilityBlock.length, withOutcome.length > 0],
    [withCapabilityBlock.length, withCapabilityBlock.length, true]);
  checkTrue("every non-null capabilityOutcome is the shared catalog OBJECT, not a copy",
    withOutcome.every((r) => r.result.capabilityOutcome === OUTCOMES.query_contract_failed));
  checkTrue("a row carrying capabilityOutcome always carries a block reason too",
    withOutcome.every((r) => ((r.result.blockReasons as string[]) ?? []).length > 0));
  checkTrue("a row with no capability block carries null, not an empty object",
    current.filter((r) => !withCapabilityBlock.includes(r))
      .every((r) => r.result.capabilityOutcome === null));
}

// ── ANTI-VACUITY: the comparison must be able to go red ─────────────────────────────────────
// A parity test that has never been observed failing is evidence that it runs, not that the
// property holds. This reclassifies one rule from block to retry through the shared authority —
// membership-preserving in total size, behaviour-changing in fact — and requires the comparison to
// notice. Then it restores and requires the comparison to be clean again.
{
  const victim = "unsupported-sub-city-geography";
  const wasBlock = BLOCK_CAPABILITY_RULES.has(victim);
  const countRowDiffs = () => {
    const now = runPostSqlGrid();
    let n = 0;
    for (let i = 0; i < baseline.length; i++) {
      const b = JSON.stringify(baseKeysOnly(baseline[i]?.result, BASE_KEYS));
      const c = JSON.stringify(baseKeysOnly(now[i]?.result, BASE_KEYS));
      if (b !== c) n++;
    }
    return n;
  };

  checkTrue("anti-vacuity precondition: the victim rule is a block rule at rest", wasBlock);
  let underMutation = -1;
  try {
    BLOCK_CAPABILITY_RULES.delete(victim);
    RETRY_CAPABILITY_RULES.add(victim);
    underMutation = countRowDiffs();
  } finally {
    RETRY_CAPABILITY_RULES.delete(victim);
    if (wasBlock) BLOCK_CAPABILITY_RULES.add(victim);
  }

  checkTrue("reclassifying one rule block -> retry makes the comparison go RED",
    underMutation > 0, `it stayed green across all ${baseline.length} rows, so it proves nothing`);
  check("and the comparison is clean again once the authority is restored", countRowDiffs(), 0);
  check("the shared sets are restored exactly",
    [BLOCK_CAPABILITY_RULES.has(victim), RETRY_CAPABILITY_RULES.has(victim),
     BLOCK_CAPABILITY_RULES.size, RETRY_CAPABILITY_RULES.size],
    [true, false, 9, 28]);
}

console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail === 0 ? 0 : 1);
