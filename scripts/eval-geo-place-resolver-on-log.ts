import Database from "better-sqlite3";
import fs from "node:fs";
import path from "node:path";
import { resolveGeoPlaces } from "../lib/geo-place-resolver";

type QueryLogRow = {
  id?: number;
  ts: number;
  tab?: string | null;
  question: string;
};

function argValue(name: string): string | null {
  const prefix = `${name}=`;
  const found = process.argv.find((arg) => arg.startsWith(prefix));
  return found ? found.slice(prefix.length) : null;
}

function dbPath(): string {
  return argValue("--db") || path.join(process.cwd(), "query_log.db");
}

function days(): number {
  const raw = argValue("--days");
  const parsed = raw ? Number(raw) : 1;
  return Number.isFinite(parsed) && parsed > 0 ? parsed : 1;
}

function outPath(): string {
  const explicit = argValue("--out");
  if (explicit) return explicit;
  const stamp = new Date().toISOString().slice(0, 10);
  return path.join(process.cwd(), "docs", `geo-place-resolver-log-frame-${stamp}.md`);
}

function main() {
  const inputDb = dbPath();
  const windowDays = days();
  const cutoff = Date.now() - windowDays * 24 * 60 * 60 * 1000;
  const db = new Database(inputDb, { readonly: true, fileMustExist: true });
  try {
    const hasId = columnExists(db, "query_log", "id");
    const idSelect = hasId ? "id" : "rowid AS id";
    const rows = db.prepare(`
      SELECT ${idSelect}, ts, tab, question
      FROM query_log
      WHERE ts >= ? AND question IS NOT NULL AND question <> ''
      ORDER BY ts ASC
    `).all(cutoff) as QueryLogRow[];

    writeReport({
      rows,
      inputDb,
      windowDays,
      cutoff,
      target: outPath(),
    });
  } finally {
    db.close();
  }
}

function columnExists(db: Database.Database, table: string, column: string): boolean {
  return db.prepare(`PRAGMA table_info(${table})`).all()
    .some((row) => (row as { name?: string }).name === column);
}

function writeReport(opts: {
  rows: QueryLogRow[];
  inputDb: string;
  windowDays: number;
  cutoff: number;
  target: string;
}) {
  const lines: string[] = [];
  let withPlaces = 0;
  let clarifications = 0;

  const evaluated = opts.rows.map((row) => {
    const result = resolveGeoPlaces(row.question);
    if (result.mentions.length > 0) withPlaces += 1;
    if (result.requiresClarification) clarifications += 1;
    return { row, result };
  });

  lines.push(`# Geo Place Resolver Log Frame - ${new Date().toISOString().slice(0, 10)}`);
  lines.push("");
  lines.push("Generated by `npx tsx scripts/eval-geo-place-resolver-on-log.ts`.");
  lines.push("");
  lines.push("- Shadow-only: no app behavior is changed.");
  lines.push(`- Database: \`${opts.inputDb}\``);
  lines.push(`- Window: last ${opts.windowDays} day(s), since ${new Date(opts.cutoff).toISOString()}`);
  lines.push(`- Queries evaluated: ${opts.rows.length}`);
  lines.push(`- Queries with place mentions: ${withPlaces}`);
  lines.push(`- Queries requiring clarification: ${clarifications}`);
  lines.push("");
  lines.push("| Log | Time | Tab | Question | Resolver Output | Clarifies |");
  lines.push("| --- | --- | --- | --- | --- | --- |");

  for (const { row, result } of evaluated) {
    if (result.mentions.length === 0 && opts.rows.length > 100) continue;
    const output = result.mentions.length
      ? result.mentions.map((mention) => {
        const candidates = mention.candidates
          .slice(0, 8)
          .map((candidate) => candidate.id)
          .join("<br>");
        const more = mention.candidates.length > 8 ? `<br>+${mention.candidates.length - 8} more` : "";
        return `**${escapeCell(mention.text)}**<br>${candidates}${more}`;
      }).join("<br><br>")
      : "none";
    lines.push(`| ${row.id ?? ""} | ${new Date(row.ts).toISOString()} | ${escapeCell(row.tab ?? "")} | ${escapeCell(row.question)} | ${output} | ${result.requiresClarification ? "yes" : "no"} |`);
  }

  lines.push("");
  lines.push("## Review Notes");
  lines.push("");
  lines.push("- Rows marked `Clarifies = yes` are candidates for future pre-submit guidance, not automatic blockers.");
  lines.push("- Review false positives before wiring any resolver output into the app.");
  lines.push("- Broad multi-state city names should stay shadow-only until ranked by frequency and user intent.");
  lines.push("");

  fs.mkdirSync(path.dirname(opts.target), { recursive: true });
  fs.writeFileSync(opts.target, `${lines.join("\n")}\n`, "utf8");
  console.log(`Wrote ${opts.target}`);
  console.log(`queries=${opts.rows.length} withPlaces=${withPlaces} clarifications=${clarifications}`);
}

function escapeCell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

main();
